#!/usr/bin/env python3
"""Counts the tokens of an MCP tool surface: each tool's definition (name, description, input
schema) and the server instructions (datumesh-local 0.5.2, item 18).

    python3 tools/mcp_tokens.py --definitions <file> [--json]
    python3 tools/mcp_tokens.py --definitions <full.json> [--small <small.json>] --report docs/mcp-tokens.md

<file> is {"instructions": <string>, "tools": <tools/list's tools array>}.

Method. With ANTHROPIC_API_KEY set, each count is the Messages count_tokens endpoint's: the
request with the tool (or the instructions as the system prompt) less the same request without
it, so the framing cancels. Without a key the count is an approximation: the characters of the
definition's canonical JSON divided by 3.5, rounded up. Its known error: a character ratio is not
the tokenizer, and schema punctuation tokenizes more densely than prose, so the approximation can
read about 20 per cent low or high for one tool; the endpoint's count is the authoritative one.
"""

import argparse
import json
import math
import os
import sys
import urllib.error
import urllib.request

APPROX_RATIO = 3.5
APPROX_METHOD = "approximation: canonical JSON characters / 3.5, rounded up (no ANTHROPIC_API_KEY)"
APPROX_ERROR = (
    "a character ratio, not the tokenizer: schema punctuation tokenizes more densely than prose, "
    "so one tool's count can be about 20 per cent low or high"
)
API_METHOD = "Anthropic count_tokens endpoint, the request with the item less the same request without it"
API_ERROR = "none beyond the endpoint's own rounding; the counts are for the model named in MODEL"
MODEL = "claude-haiku-5-5"
API = "https://api.anthropic.com/v1/messages/count_tokens"


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def tool_body(tool):
    return {
        "name": tool["name"],
        "description": tool.get("description", ""),
        "input_schema": tool.get("inputSchema", {"type": "object"}),
    }


def approx(text):
    return math.ceil(len(text) / APPROX_RATIO)


class Api:
    def __init__(self, key):
        self.key = key

    def count(self, messages, system=None, tools=None):
        body = {"model": MODEL, "messages": messages}
        if system is not None:
            body["system"] = system
        if tools is not None:
            body["tools"] = tools
        req = urllib.request.Request(
            API,
            data=json.dumps(body).encode("utf-8"),
            headers={
                "x-api-key": self.key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8"))["input_tokens"]


def count_all(definitions, key):
    """(method, known error, {tool: tokens}, instructions tokens) for a definitions object."""
    tools = definitions["tools"]
    instructions = definitions.get("instructions", "")
    if key:
        try:
            api = Api(key)
            base = [{"role": "user", "content": "x"}]
            none = api.count(base)
            per = {}
            for t in tools:
                per[t["name"]] = max(1, api.count(base, tools=[tool_body(t)]) - none)
            instr = max(1, api.count(base, system=instructions) - none)
            return API_METHOD, API_ERROR, per, instr
        except (urllib.error.URLError, OSError, KeyError, ValueError) as e:
            print(f"count_tokens failed ({e}); using the approximation", file=sys.stderr)
    per = {t["name"]: approx(canonical(tool_body(t))) for t in tools}
    return APPROX_METHOD, APPROX_ERROR, per, approx(instructions)


def table(label, method, per, instr, total):
    lines = [f"{label}:"]
    for name, n in per.items():
        lines.append(f"  {name:<16} {n:>6}")
    lines.append(f"  {'instructions':<16} {instr:>6}")
    lines.append(f"  {'total':<16} {total:>6}")
    lines.append(f"  method: {method}")
    return "\n".join(lines)


def report(path, full, small, key):
    out = ["# MCP tool tokens", ""]
    out.append(
        "Generated by `tools/mcp_tokens.py --definitions <the default surface> --small <the small surface> "
        "--report docs/mcp-tokens.md`, from `datumesh mcp --profile full` and `--profile small` (their "
        "`tools/list` and instructions). Regenerate it when the tool surface changes."
    )
    out.append("")
    for label, definitions in (("The default surface (`--profile full`)", full), ("The small profile (`--profile small`)", small)):
        method, err, per, instr = count_all(definitions, key)
        total = sum(per.values()) + instr
        out.append(f"## {label}")
        out.append("")
        out.append("| Item | Tokens |")
        out.append("| --- | ---: |")
        for name, n in per.items():
            out.append(f"| `{name}` | {n} |")
        out.append(f"| instructions | {instr} |")
        out.append(f"| **total** | **{total}** |")
        out.append("")
        out.append(f"Method: {method}. Known error: {err}.")
        out.append("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--definitions", required=True, help="the surface: {instructions, tools}")
    ap.add_argument("--json", action="store_true", help="print one JSON object")
    ap.add_argument("--small", help="the small profile's surface, for --report")
    ap.add_argument("--report", help="write the Markdown report to this file")
    a = ap.parse_args(argv)
    key = os.environ.get("ANTHROPIC_API_KEY")
    with open(a.definitions, encoding="utf-8") as f:
        full = json.load(f)
    if a.report:
        small_def = full
        if a.small:
            with open(a.small, encoding="utf-8") as f:
                small_def = json.load(f)
        report(a.report, full, small_def, key)
        print(f"wrote {a.report}")
        return 0
    method, err, per, instr = count_all(full, key)
    total = sum(per.values()) + instr
    if a.json:
        print(json.dumps({"method": method, "known_error": err, "tools": per, "instructions": instr, "total": total},
                         separators=(",", ":")))
    else:
        print(table("datumesh MCP surface", method, per, instr, total))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
